-- ============================================================================
--  تِبيان — إعداد قاعدة البيانات ونظام مراجعة التلاوات قبل النشر
--  التصميم والتطوير: سور للبرمجيات
--
--  طريقة التشغيل:
--    Supabase → SQL Editor → الصقي الملف كاملًا → Run
--  الملف آمن لإعادة التشغيل أكثر من مرة.
--
--  ملاحظة مهمة: هذا الملف يحذف سياسات RLS القديمة على جداول
--  (videos, video_reviews, volunteers, review_settings, channels,
--   channel_requests, admin_users) وسياسات التخزين الخاصة بحاوية
--  tibyan-videos، ثم ينشئ سياسات جديدة تمنع نشر أي تلاوة قبل مراجعتها.
--
--  مسار النشر:
--    1) صاحب القناة المعتمدة يرفع التلاوة  ← الحالة pending (قيد المراجعة)
--    2) المتطوعون يستمعون ويصوّتون (موافقة / رفض مع ملاحظة)
--    3) الإدارة تتخذ القرار النهائي، ولا يمكنها النشر قبل اكتمال
--       العدد المطلوب من موافقات المتطوعين (الافتراضي: 1)
--    4) الحالة published ← تظهر للزوار
--  أي تعديل على محتوى تلاوة منشورة يعيدها تلقائيًا إلى المراجعة.
-- ============================================================================

