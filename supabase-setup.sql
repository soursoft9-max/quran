  using (user_id = auth.uid() or public.is_admin());

create policy channel_requests_insert on public.channel_requests
  for insert to authenticated
  with check (user_id = auth.uid() and status = 'pending');

-- يمكن لصاحب الطلب المرفوض حذفه ليقدّم طلبًا جديدًا
create policy channel_requests_delete on public.channel_requests
  for delete to authenticated
  using ((user_id = auth.uid() and status = 'rejected') or public.is_admin());

create policy channel_requests_admin_update on public.channel_requests
  for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- القنوات: المعتمدة للجميع
create policy channels_select on public.channels
  for select
  using (status = 'approved' or user_id = auth.uid() or public.is_admin());

create policy channels_admin_write on public.channels
  for all to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- التلاوات: الزوار يرون المنشورة فقط
create policy videos_select on public.videos
  for select
  using (status = 'published' or user_id = auth.uid() or public.is_reviewer());

-- الرفع لأصحاب القنوات المعتمدة والإدارة فقط (والحالة تُفرض pending بالمحفّز)
create policy videos_insert on public.videos
  for insert to authenticated
  with check (
    user_id = auth.uid()
    and status in ('pending', 'draft')
    and (public.is_admin() or public.has_approved_channel(auth.uid()))
  );

create policy videos_update on public.videos
  for update to authenticated
  using (user_id = auth.uid() or public.is_admin())
  with check (user_id = auth.uid() or public.is_admin());

create policy videos_delete on public.videos
  for delete to authenticated
  using (user_id = auth.uid() or public.is_admin());

