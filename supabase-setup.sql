  using (public.is_reviewer());

-- ---------------------------------------------------------------------------
-- 9) التخزين: الحاوية خاصة، والملفات غير المنشورة لا يصل إليها إلا
--    صاحبها والمراجعون
-- ---------------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('tibyan-videos', 'tibyan-videos', false)
on conflict (id) do update set public = false;

do $$
declare r record;
begin
  for r in
    select policyname from pg_policies
    where schemaname = 'storage' and tablename = 'objects'
      and (coalesce(qual, '') ilike '%tibyan-videos%'
           or coalesce(with_check, '') ilike '%tibyan-videos%')
  loop
    execute format('drop policy if exists %I on storage.objects', r.policyname);
  end loop;
end $$;

-- القراءة (ومنها إنشاء روابط التشغيل المؤقتة)
create policy tibyan_objects_select on storage.objects
  for select to anon, authenticated
  using (
    bucket_id = 'tibyan-videos'
    and (
      public.is_reviewer()
      or (storage.foldername(objects.name))[1] = auth.uid()::text
      or exists (
        select 1 from public.videos v
        where v.status = 'published'
          and (v.video_url = objects.name or v.thumbnail_url = objects.name)
      )
    )
  );

-- الرفع داخل مجلد المستخدم فقط: <user_id>/videos/... و <user_id>/thumbnails/...
create policy tibyan_objects_insert on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'tibyan-videos'
    and (storage.foldername(objects.name))[1] = auth.uid()::text
    and (public.is_admin() or public.has_approved_channel(auth.uid()))
  );

-- لا توجد سياسة UPDATE: لا يمكن استبدال ملف بعد اعتماده.
create policy tibyan_objects_delete on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'tibyan-videos'
    and ((storage.foldername(objects.name))[1] = auth.uid()::text or public.is_admin())
  );

commit;

