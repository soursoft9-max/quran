-- تصويت المتطوع (أو المدير) على تلاوة قيد المراجعة
create or replace function public.submit_video_review(
  p_video_id text, p_decision text, p_notes text default null)
returns json language plpgsql security definer set search_path = public as $$
declare
  v    record;
  role text;
begin
  if not public.is_reviewer() then
    raise exception 'هذه العملية متاحة للمتطوعين والإدارة فقط.';
  end if;
  if p_decision not in ('approve', 'reject') then
    raise exception 'قرار غير صالح.';
  end if;

  select id, user_id, status into v from public.videos where id::text = p_video_id;
  if not found then raise exception 'التلاوة غير موجودة.'; end if;
  if v.status <> 'pending' then raise exception 'هذه التلاوة ليست قيد المراجعة.'; end if;
  if v.user_id = auth.uid() then raise exception 'لا يمكنك مراجعة تلاوة رفعتها بنفسك.'; end if;
  if p_decision = 'reject' and coalesce(trim(p_notes), '') = '' then
    raise exception 'يرجى كتابة سبب الرفض.';
  end if;

  role := case when public.is_volunteer() then 'volunteer' else 'admin' end;

  insert into public.video_reviews (video_id, reviewer_id, reviewer_role, decision, notes)
  values (v.id, auth.uid(), role, p_decision, nullif(trim(p_notes), ''))
  on conflict (video_id, reviewer_id) do update
    set decision      = excluded.decision,
        notes         = excluded.notes,
        reviewer_role = excluded.reviewer_role,
        updated_at    = now();

  return json_build_object(
    'approvals', public.volunteer_approvals(p_video_id),
    'required',  public.required_approvals());
end $$;

-- القرار النهائي للإدارة: publish | reject | unpublish
create or replace function public.admin_decide_video(
  p_video_id text, p_decision text, p_note text default null)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then
    raise exception 'القرار النهائي متاح لإدارة تِبيان فقط.';
  end if;

  if p_decision = 'publish' then
    update public.videos
      set status = 'published', review_note = nullif(trim(p_note), '')
      where id::text = p_video_id;
  elsif p_decision = 'reject' then
    if coalesce(trim(p_note), '') = '' then
      raise exception 'يرجى كتابة سبب الرفض ليصل إلى صاحب التلاوة.';
    end if;
    update public.videos
      set status = 'rejected', review_note = trim(p_note)
      where id::text = p_video_id;
  elsif p_decision = 'unpublish' then
    update public.videos
      set status = 'pending', review_note = nullif(trim(p_note), '')
      where id::text = p_video_id;
  else
    raise exception 'قرار غير صالح.';
  end if;

  if not found then raise exception 'التلاوة غير موجودة.'; end if;
end $$;

-- طلبات القنوات
create or replace function public.approve_channel_request(p_request_id text)
returns void language plpgsql security definer set search_path = public as $$
declare r record;
begin
  if not public.is_admin() then raise exception 'هذه العملية متاحة لإدارة تِبيان فقط.'; end if;

  select * into r from public.channel_requests where id::text = p_request_id;
  if not found then raise exception 'الطلب غير موجود.'; end if;

  update public.channel_requests
    set status = 'approved', reviewed_at = now(), admin_note = null
    where id = r.id;

  update public.channels
    set status = 'approved', channel_name = r.channel_name,
        description = coalesce(r.description, description)
    where user_id = r.user_id;

  if not found then
    insert into public.channels (user_id, channel_name, description, status)
    values (r.user_id, r.channel_name, r.description, 'approved');
  end if;
end $$;

create or replace function public.reject_channel_request(p_request_id text, p_note text default null)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'هذه العملية متاحة لإدارة تِبيان فقط.'; end if;
  update public.channel_requests
    set status = 'rejected', reviewed_at = now(), admin_note = nullif(trim(p_note), '')
    where id::text = p_request_id;
  if not found then raise exception 'الطلب غير موجود.'; end if;
end $$;

create or replace function public.set_channel_status(p_channel_id text, p_status text)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'هذه العملية متاحة لإدارة تِبيان فقط.'; end if;
  if p_status not in ('approved', 'suspended') then raise exception 'حالة غير صالحة.'; end if;
  update public.channels set status = p_status where id::text = p_channel_id;
  if not found then raise exception 'القناة غير موجودة.'; end if;
end $$;

-- إدارة المتطوعين
create or replace function public.add_volunteer(p_email text)
returns json language plpgsql security definer set search_path = public as $$
declare u record;
begin
  if not public.is_admin() then raise exception 'هذه العملية متاحة لإدارة تِبيان فقط.'; end if;

  select id, email into u from auth.users where lower(email) = lower(trim(p_email));
  if not found then
    raise exception 'لا يوجد حساب بهذا البريد. يجب أن يُنشئ المتطوع حسابًا في تِبيان أولًا.';
  end if;

  insert into public.volunteers (user_id, email, active, added_by)
  values (u.id, u.email, true, auth.uid())
  on conflict (user_id) do update set active = true, email = excluded.email;

  return json_build_object('user_id', u.id, 'email', u.email);
end $$;

create or replace function public.remove_volunteer(p_user_id uuid)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'هذه العملية متاحة لإدارة تِبيان فقط.'; end if;
  delete from public.volunteers where user_id = p_user_id;
end $$;

create or replace function public.set_required_approvals(p_count integer)
returns void language plpgsql security definer set search_path = public as $$
begin
  if not public.is_admin() then raise exception 'هذه العملية متاحة لإدارة تِبيان فقط.'; end if;
  if p_count < 0 or p_count > 20 then raise exception 'العدد يجب أن يكون بين 0 و 20.'; end if;
  update public.review_settings
    set required_volunteer_approvals = p_count, updated_at = now()
    where id = 1;
end $$;

